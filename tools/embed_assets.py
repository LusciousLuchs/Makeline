#!/usr/bin/env python3
"""Embeds the studio logo and the game's font into src/game/assets.inc, so the game is a single .exe."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
def arr(name, path):
    data = open(os.path.join(ROOT, path), 'rb').read()
    out = [f'static const unsigned char {name}[{len(data)}] = {{']
    for k in range(0, len(data), 40):
        out.append(','.join(str(b) for b in data[k:k + 40]) + ',')
    out.append('};')
    return '\n'.join(out)
text = '// GENERATED by tools/embed_assets.py. Do not edit.\n' + arr('OAB_LOGO_JPG', 'assets/logo/oab_foundry.jpg') + '\n' + arr('FONT_OTF', 'third_party/fonts/inter/Inter-SemiBold.otf') + '\n'
open(os.path.join(ROOT, 'src', 'game', 'assets.inc'), 'w').write(text)
print('wrote src/game/assets.inc')
